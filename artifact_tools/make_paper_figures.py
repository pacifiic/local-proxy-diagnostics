def make_direct_tilt_summeval_tight():
    data_path = _first_existing(DATA_ROOT / "summeval_long.csv", ROOT / "data" / "summeval_long.csv")
    if data_path is None:
        print(f"  Skipping direct-tilt example (summeval_long.csv not found under {DATA_ROOT})")
        return

    coef_path = _first_existing(
        RESULTS / "builder_cache" / "tables" / "table_direct_tilt_summeval.csv",
        RESULTS / "02_corrected_coefficients" / "table_direct_tilt_summeval.csv",
    )

    df = pd.read_csv(data_path)
    df["item_id"] = df["article_id"].astype(str) + "___" + df["model_id"].astype(str)
    sub = df[(df["rater_type"].isin(["expert"])) & (df["dimension"] == "consistency")]
    if sub.empty:
        print("  Skipping direct-tilt example (SummEval expert/consistency slice missing)")
        return

    X = sub.pivot_table(index="item_id", columns="rater_idx", values="score", aggfunc="first").dropna()
    if X.shape[1] < 2:
        print("  Skipping direct-tilt example (not enough raters)")
        return
    mat = X.to_numpy(float)
    r = mat[:, 0]
    J = (mat.sum(axis=1) - r) / (mat.shape[1] - 1)

    t_grid = np.concatenate([[0.0], np.geomspace(1e-5, 4.0, 400)])
    d, q = _tilt_curve(J, r, t_grid)
    gain = q - q[0]
    A_th, B_th = _compute_ab(J, r)
    A_fit, B_fit = _fit_local(d, q, 0.20)

    if coef_path is not None:
        coefs = pd.read_csv(coef_path)
        row = coefs[
            (coefs["label"] == "exp-consi")
            & (coefs["rater_idx"] == 0)
            & np.isclose(coefs["fit_max_d"], 0.20)
        ]
        if not row.empty:
            A_th = float(row.iloc[0]["A_theory"])
            B_th = float(row.iloc[0]["B_theory"])
            A_fit = float(row.iloc[0]["A_fit"])
            B_fit = float(row.iloc[0]["B_fit"])

    # Do not draw prediction curves beyond the computed exact path.
    max_d = float(d.max())
    attainable_d = float(-np.log(np.mean(r == r.max())))
    mask = d <= max_d
    d_smooth = np.linspace(0, max_d, 240)

    fig, ax = plt.subplots(figsize=(5.8, 3.8))
    ax.plot(d[mask], gain[mask], color="black", linewidth=2.1, label="Exact tilt")
    ax.plot(
        d_smooth,
        A_th * np.sqrt(d_smooth) + B_th * d_smooth,
        color="#D32F2F",
        linestyle="--",
        linewidth=1.8,
        label=f"Theory: A={A_th:.2f}, B={B_th:.2f}",
    )
    ax.plot(
        d_smooth,
        A_fit * np.sqrt(d_smooth) + B_fit * d_smooth,
        color="#1976D2",
        linestyle=":",
        linewidth=2.0,
        label=f"Fit: A={A_fit:.2f}, B={B_fit:.2f}",
    )
    ax.axvspan(0, 0.10, color="#E3F2FD", alpha=0.45, zorder=-5)
    ax.axvline(0.10, color="#1565C0", linestyle="--", linewidth=1.0,
               label="Checked window: d = 0.10")
    ax.axvline(0.20, color="gray", linestyle="-.", linewidth=1.0,
               label="Nominal fit cutoff: d = 0.20")
    ax.axvspan(attainable_d, 0.22, color="#eeeeee", zorder=-4)
    ax.text((attainable_d + 0.22) / 2, 0.98, "Unattainable",
            transform=ax.get_xaxis_transform(), ha="center", va="top", fontsize=8)
    ax.set_xlim(0, 0.22)
    ax.set_xlabel("KL radius $d$")
    ax.set_ylabel("$Q(d)-Q(0)$")
    ax.set_title("SummEval expert consistency: exact tilt vs local law", fontsize=11)
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8, loc="lower right")
    plt.tight_layout()
    out = OUTDIR / "fig_direct_tilt_summeval_tight.pdf"
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


