def _first_existing(*paths: Path) -> Path | None:
    for path in paths:
        if path.exists():
            return path
    return None


def _overall_row(csv_path: Path) -> pd.Series | None:
    if not csv_path.exists():
        return None
    df = pd.read_csv(csv_path)
    if "group_key" in df.columns:
        sub = df[df["group_key"] == "__OVERALL__"]
    elif "target_group_key" in df.columns:
        sub = df[df["target_group_key"] == "__OVERALL__"]
    else:
        sub = df.tail(1)
    if sub.empty:
        return None
    return sub.iloc[-1]


def _ci_from_row(row: pd.Series, lo_col: str, hi_col: str) -> tuple[float, float] | None:
    if lo_col not in row or hi_col not in row:
        return None
    lo = row[lo_col]
    hi = row[hi_col]
    if pd.isna(lo) or pd.isna(hi):
        return None
    return float(lo), float(hi)


def _cluster_bootstrap_mean_ci(
    df: pd.DataFrame,
    value_col: str,
    group_col: str | None = None,
    *,
    n_boot: int = 1000,
    seed: int = 0,
) -> tuple[float, float, float]:
    values = pd.to_numeric(df[value_col], errors="coerce")
    work = df.loc[values.notna()].copy()
    work[value_col] = values[values.notna()]
    if work.empty:
        return np.nan, np.nan, np.nan
    if group_col is not None and group_col in work.columns:
        grouped = work.groupby(group_col, dropna=False)[value_col]
        group_sums = grouped.sum().to_numpy(float)
        group_counts = grouped.count().to_numpy(float)
    else:
        group_sums = work[value_col].to_numpy(float)
        group_counts = np.ones(len(work), dtype=float)
    mean = float(work[value_col].mean())
    if len(group_sums) < 2:
        return mean, mean, mean
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(group_sums), size=(n_boot, len(group_sums)))
    boot = group_sums[idx].sum(axis=1) / group_counts[idx].sum(axis=1)
    lo, hi = np.quantile(boot, [0.025, 0.975])
    return mean, float(lo), float(hi)


def _main_ood_zcal_values() -> tuple[list[str], np.ndarray, np.ndarray | None] | None:
    """Load the Figure 1 OOD panel from the same z_cal table used in the paper."""
    table_path = TABLES_ROOT / "table_ood_lambda_sweep.csv"
    if not table_path.exists():
        return None
    table = pd.read_csv(table_path)
    route_mask = table["Route"].astype(str).eq("SummEval -> WMT clusters")
    lambda_mask = pd.to_numeric(table["$\\lambda$"], errors="coerce").eq(0.75)
    row = table.loc[route_mask & lambda_mask]
    if row.empty:
        return None
    row = row.iloc[0]

    labels = ["source\nonly", "source\nprior", "target\ncal", "target\n$A_\\nu$", "zero"]
    table_cols = ["Source-only", "Source-prior", "Target cal.", "$A_\\nu$", "Zero"]
    vals = np.array([float(row[col]) for col in table_cols])

    paths_path = _first_existing(
        RESULTS / "13_robustness" / "ood_summeval_to_wmt_lambda_0p75" / "exp31_ood_transfer_paths.csv",
        RESULTS / "extended_analyses" / "ood_summeval_to_wmt_lambda_0p75" / "exp31_ood_transfer_paths.csv",
    )
    yerr = None
    if paths_path is not None:
        paths = pd.read_csv(paths_path)
        err_cols = [
            "abs_err_source_mean_0p1",
            "abs_err_source_prior_0p1",
            "abs_err_target_cal_0p1",
            "abs_err_target_anu_0p1",
            "abs_err_zero_0p1",
        ]
        if all(col in paths.columns for col in err_cols):
            ci_rows = [
                _cluster_bootstrap_mean_ci(paths, col, "target_path_id", n_boot=2000, seed=0)
                for col in err_cols
            ]
            lo = np.array([row[1] for row in ci_rows])
            hi = np.array([row[2] for row in ci_rows])
            if np.isfinite(lo).all() and np.isfinite(hi).all():
                yerr = np.vstack([vals - lo, hi - vals])
    return labels, vals, yerr


def _compute_ab(J, r):
    J = np.asarray(J, float)
    r = np.asarray(r, float)
    Jc = J - J.mean()
    rc = r - r.mean()
    sigma_J_sq = np.mean(Jc**2)
    sigma_r_sq = np.mean(rc**2)
    sigma_r = np.sqrt(sigma_r_sq)
    eps = r - J
    rho = np.mean(Jc * (eps - eps.mean()))
    kappa_r = np.mean(rc**3)
    kappa_Jrr = np.mean(Jc * rc**2)
    A = np.sqrt(2) * (sigma_J_sq + rho) / sigma_r
    B = kappa_Jrr / sigma_r_sq - 2 * (sigma_J_sq + rho) * kappa_r / (3 * sigma_r_sq**2)
    return A, B


def _tilt_curve(J, r, t_grid):
    J = np.asarray(J, float)
    r = np.asarray(r, float)
    n = len(r)
    d_vals, q_vals = [], []
    for t in t_grid:
        logits = t * r
        shifted = logits - np.max(logits)
        weights = np.exp(shifted)
        pi = weights / weights.sum()
        log_pi = np.log(pi + 1e-300)
        d_vals.append(float(np.dot(pi, log_pi + np.log(n))))
        q_vals.append(float(np.dot(pi, J)))
    return np.asarray(d_vals), np.asarray(q_vals)


def _fit_local(d, q, max_d):
    mask = (d > 1e-10) & (d <= max_d)
    if mask.sum() < 2:
        return np.nan, np.nan
    X = np.column_stack([np.sqrt(d[mask]), d[mask]])
    y = q[mask] - q[0]
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    return float(coef[0]), float(coef[1])


