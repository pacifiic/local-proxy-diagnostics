def _copy_pdf(src: Path, dst_name: str) -> bool:
    dst = OUTDIR / dst_name
    if not src.exists():
        print(f"  Skipping {dst_name} (file not found): {src}")
        return False
    OUTDIR.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    print(f"  Copied: {src} -> {dst}")
    return True


def _embed_png_as_pdf(src: Path, dst_name: str) -> bool:
    if not src.exists():
        return False
    from PIL import Image

    dst = OUTDIR / dst_name
    OUTDIR.mkdir(parents=True, exist_ok=True)
    with Image.open(src) as img:
        if img.mode in {"RGBA", "LA", "P"}:
            img = img.convert("RGB")
        img.save(dst, "PDF", resolution=300.0)
    print(f"  Embedded PNG as PDF: {src} -> {dst}")
    return True


def _copy_or_convert_legacy_figure(stem: str, dst_name: str | None = None) -> bool:
    """Copy a preserved legacy PDF, or embed its preserved PNG in a PDF.

    Legacy experiment scripts historically wrote several appendix figures to
    results/figures.  The reproduction runner preserves those files under
    builder_cache/figures; this helper keeps the paper artifact
    builder from silently redrawing a different-looking vector figure from the
    same summary table.
    """
    dst_name = dst_name or f"{stem}.pdf"
    png_candidates = [
        RESULTS / "builder_cache" / "figures" / f"{stem}.png",
        RESULTS / "02_corrected_coefficients" / f"{stem}.png",
    ]
    for src in png_candidates:
        if _embed_png_as_pdf(src, dst_name):
            return True

    candidates = [
        ROOT / "verification" / "reference_figures" / f"{stem}.pdf",
        RESULTS / "builder_cache" / "figures" / f"{stem}.pdf",
        RESULTS / "02_corrected_coefficients" / f"{stem}.pdf",
    ]
    for src in candidates:
        if _copy_pdf(src, dst_name):
            return True

    print(f"  Skipping {dst_name} (legacy source not found for {stem})")
    return False


