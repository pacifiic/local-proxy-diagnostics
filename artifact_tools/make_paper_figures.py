def _normalize_pdf_metadata_in_dir(path: Path) -> tuple[int, int, int, int]:
    """Normalize volatile PDF date metadata without changing xref offsets."""
    files_seen = files_changed = date_fields_changed = skipped_fields = 0
    for pdf in sorted(path.glob("*.pdf")):
        files_seen += 1
        data = pdf.read_bytes()
        local_changes = 0
        local_skipped = 0

        def replace_date(match: re.Match[bytes]) -> bytes:
            nonlocal local_changes, local_skipped
            value = match.group(3)
            if len(value) != len(CANONICAL_PDF_DATE):
                local_skipped += 1
                return match.group(0)
            if value == CANONICAL_PDF_DATE:
                return match.group(0)
            local_changes += 1
            return match.group(1) + CANONICAL_PDF_DATE + match.group(4)

        normalized = PDF_DATE_FIELD_RE.sub(replace_date, data)
        skipped_fields += local_skipped
        date_fields_changed += local_changes
        if normalized != data:
            pdf.write_bytes(normalized)
            files_changed += 1
    return files_changed, files_seen, date_fields_changed, skipped_fields


