def main():
    ap = argparse.ArgumentParser(
        description="Generate current paper figures.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument(
        "--results", type=Path,
        default=ROOT / "results",
        help=(
            "Root results directory (default: results). "
            "Figures 1-2 need subfolders 01_icc_decomposition and "
            "02_corrected_coefficients; later figures need subfolders 05-13."
        ),
    )
    ap.add_argument(
        "--figures", type=Path,
        default=ROOT / "artifacts/figures",
        help="Output directory for all generated figures.",
    )
    ap.add_argument(
        "--tables-root", type=Path,
        default=ROOT / "artifacts/tables",
        help="Generated table directory used by figure inputs.",
    )
    ap.add_argument(
        "--data-root", type=Path,
        default=ROOT / "data",
        help="Root data directory, used for the compact direct-tilt example.",
    )
    ap.add_argument(
        "--include-legacy-unused",
        action="store_true",
        help="Also generate older standalone figures no longer referenced by the current paper source.",
    )
    ap.add_argument("--only", nargs="+", help="Generate only the named PDF stems.")
    args = ap.parse_args()

    global OUTDIR, RESULTS, DATA_ROOT, TABLES_ROOT
    RESULTS = args.results
    OUTDIR  = args.figures
    DATA_ROOT = args.data_root
    TABLES_ROOT = args.tables_root
    OUTDIR.mkdir(parents=True, exist_ok=True)

    print(f"Results dir : {RESULTS}")
    print(f"Figures dir : {OUTDIR}")
    print(f"Data root   : {DATA_ROOT}")
    print()

    legacy_tasks = [
        ("fig_gpt_diagnostic_bars.pdf", make_gpt_diagnostic_bars),
        ("fig_ood_mae.pdf", fix_ood_mae),
        ("fig_prediction_mae.pdf", fix_prediction_mae),
    ]
    current_tasks = [
        ("fig1_summeval_icc_by_dimension.pdf", make_fig1_summeval_icc_by_dimension),
        ("fig2_summeval_personalization_gap.pdf", make_fig2_summeval_personalization_gap),
        ("fig3_expert_vs_crowd_lift.pdf", make_fig3_expert_vs_crowd_lift),
        ("fig4_expert_vs_crowd_scatter.pdf", make_fig4_expert_vs_crowd_scatter),
        ("fig5_protocol_split_half_stability.pdf", make_fig5_protocol_split_half_stability),
        ("fig_headroom_vs_reliability.pdf", make_figB_delta_J_max_vs_icc_scatter),
        ("fig_rewardbench_margin_geometry.pdf", make_fig07_rewardbench_B),
        ("fig_bon_bridge_coefficients.pdf", make_bon_bridge_bootstrap),
        ("fig_reward_overoptimization_comparison.pdf", make_fig09_gao_comparison),
        ("fig_corrected_B.pdf", fix_corrected_B),
        ("fig6_dataset_replication.pdf", fix_fig6_dataset_replication),
        ("fig_proxy_perturbation.pdf", fix_proxy_perturbation),
        ("fig_prediction_mae_multidataset.pdf", make_prediction_multidataset),
        ("fig_proxy_perturbation_multidataset.pdf", make_proxy_perturbation_multidataset),
        ("fig_stability_multidataset.pdf", make_stability_multidataset),
        ("fig_direct_tilt_summeval_tight.pdf", make_direct_tilt_summeval_tight),
        ("fig_main_results.pdf", make_main_results_v2),
        ("accept_boost_alias_figures", make_accept_boost_alias_figures),
    ]
    tasks = current_tasks
    if args.include_legacy_unused:
        tasks = legacy_tasks + current_tasks

    if args.only:
        wanted = set(args.only)
        known = {Path(name).stem for name, _ in tasks}
        if wanted - known:
            ap.error(f"Unknown figure stems: {sorted(wanted - known)}")
        tasks = [(name, fn) for name, fn in tasks if Path(name).stem in wanted]
    total = len(tasks)
    for idx, (name, fn) in enumerate(tasks, start=1):
        print(f"[{idx}/{total}] {name}")
        fn()

    files_changed, files_seen, date_fields_changed, skipped_fields = _normalize_pdf_metadata_in_dir(OUTDIR)
    print(
        "Normalized PDF metadata: "
        f"{files_changed}/{files_seen} files changed, "
        f"{date_fields_changed} date fields, "
        f"{skipped_fields} skipped fields."
    )

    print()
    print("Done.")


if __name__ == "__main__":
    main()
