    human = _overall_row(pred_dir / "exp27_human_baseline" / "exp27_prospective_summary.csv")
    gpt = _overall_row(pred_dir / "exp27_model_proxy_4o" / "exp27_prospective_summary.csv")
    ood_panel = _main_ood_zcal_values()
    if any(row is None for row in [human, gpt]) or ood_panel is None:
        print("  Skipping main composite (missing prediction/OOD inputs)")
        return

    fig, axes = plt.subplots(1, 2, figsize=(9.3, 3.75))

    # Panel A: prospective MAE contrast.
    ax = axes[0]
    setting_labels = ["SummEval\nhuman proxy", "GPT-4o proxy"]
    setting_rows = [human, gpt]
    x = np.arange(len(setting_labels))
    width = 0.13
    offsets = (np.arange(len(PREDICTIVE_BASELINES)) - (len(PREDICTIVE_BASELINES) - 1) / 2) * width
    max_y = 0.0
    for offset, (key, label, color) in zip(offsets, PREDICTIVE_BASELINES):
        vals = np.array([float(row[f"mae_{key}_0p1"]) for row in setting_rows])
        lo_vals = []
        hi_vals = []
        has_ci = True
        for row, val in zip(setting_rows, vals):
            ci = _ci_from_row(row, f"abs_err_{key}_0p1_ci_lo", f"abs_err_{key}_0p1_ci_hi")
            if ci is None:
                has_ci = False
                break
            lo, hi = ci
            lo_vals.append(lo)
            hi_vals.append(hi)
        yerr = None
        if has_ci:
            lo_arr = np.asarray(lo_vals)
            hi_arr = np.asarray(hi_vals)
            yerr = [vals - lo_arr, hi_arr - vals]
            max_y = max(max_y, float(np.max(hi_arr)))
        else:
            hi_arr = vals
            max_y = max(max_y, float(np.max(vals)))
        bars = ax.bar(
            x + offset,
            vals,
            width,
            label=label,
            color=color,
            alpha=0.86,
            yerr=yerr,
            error_kw=dict(ecolor="black", capsize=2, linewidth=0.8) if has_ci else {},
        )
        for bar, val, hi in zip(bars, vals, hi_arr):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                hi + max_y * 0.020,
                f"{val:.3f}",
                ha="center",
                va="bottom",
                fontsize=6.2,
            )
    ax.set_xticks(x)
    ax.set_xticklabels(setting_labels, fontsize=8.5)
    ax.set_ylabel("MAE at $d=0.10$")
    _paper_title(ax, "Prospective prediction")
    _panel_label(ax, "A")
    ax.grid(axis="y", alpha=0.3)
    ax.set_ylim(0, max_y * 1.22)
    ax.legend(fontsize=7.5, ncol=2, frameon=False, loc="upper right")

    # Panel B: OOD transfer.
    ax = axes[1]
    ood_labels, ood_vals, ood_yerr = ood_panel
    x2 = np.arange(len(ood_labels))
    ood_colors = ["#1976D2", "#43A047", "#43A047", "#EF5350", "#9E9E9E"]
    bars = ax.bar(
        x2,
        ood_vals,
        color=ood_colors,
        alpha=0.86,
        yerr=ood_yerr,
        error_kw=dict(ecolor="black", capsize=3, linewidth=1.0) if ood_yerr is not None else {},
    )
    ax.set_xticks(x2)
    ax.set_xticklabels(ood_labels, fontsize=8)
    ax.set_ylabel("MAE at $d=0.10$")
    _paper_title(ax, "SummEval to WMT OOD")
    _panel_label(ax, "B")
    ax.grid(axis="y", alpha=0.3)
    if ood_yerr is not None:
        label_base = ood_vals + np.asarray(ood_yerr[1])
    else:
        label_base = ood_vals
    label_y = label_base + max(ood_vals) * 0.030
    ax.set_ylim(0, max(max(ood_vals) * 1.24, float(np.max(label_y)) * 1.08))
    for bar, val, y in zip(bars, ood_vals, label_y):
        ax.text(bar.get_x() + bar.get_width() / 2, y, f"{val:.3f}",
                ha="center", va="bottom", fontsize=7.5)

    plt.tight_layout()
    out = OUTDIR / "fig_main_results.pdf"
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


